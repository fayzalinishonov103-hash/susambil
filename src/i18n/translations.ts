export const getTranslation = (lang: Language, key: string): string => {
  const dict = TRANSLATIONS[lang];
  if (dict && dict[kKey(key)]) {
    return dict[kKey(key)];
  }
  const uzDict = TRANSLATIONS['uz'];
  if (uzDict && uzDict[kKey(key)]) {
    return uzDict[kKey(key)];
  }
  const enDict = TRANSLATIONS['en'];
  if (enDict && enDict[kKey(key)]) {
    return enDict[kKey(key)];
  }
  return '';
};

function kKey(k: string): string {
  return k;
}

export const getLocalizedDestination = (
  destId: string,
  lang: Language,
  fallbackName: string,
  fallbackTagline: string
): { name: string; tagline: string } => {
  const custom = DESTINATION_NAMES_15[destId]?.[lang];
  if (custom) return custom;
  const uzCustom = DESTINATION_NAMES_15[destId]?.['uz'];
  if (uzCustom) return uzCustom;
  return { name: fallbackName, tagline: fallbackTagline };
};
