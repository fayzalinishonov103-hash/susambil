// Helper to inject keys into a language block
function injectKeys(fullText, langCode, keysObj) {
  // Find regex for `  langCode: {`
  const regex = new RegExp(`(\\n\\s{2}${langCode}: \\{[\\s\\S]*?)(\\n\\s{2}\\},)`, 'm');
  const match = fullText.match(regex);
  if (!match) {
    console.warn(`Could not find language block for ${langCode}`);
    return fullText;
  }

  const existingBlock = match[1];
  let additions = '';
  for (const [k, v] of Object.entries(keysObj)) {
    // Only add if not already present in this block
    if (!existingBlock.includes(`    ${k}:`)) {
      const cleanVal = String(v).replace(/'/g, "\\'");
      additions += `    ${k}: '${cleanVal}',\n`;
    }
  }

  if (!additions) return fullText;

  const newBlock = `${existingBlock}\n${additions}  },`;
  return fullText.replace(match[0], newBlock);
}

